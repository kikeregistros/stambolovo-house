// Set up Language Selectors & Logic (Flags)
function setupLanguage() {
  const flagBtns = document.querySelectorAll(".lang-flag-btn");

  flagBtns.forEach(btn => {
    btn.addEventListener("click", () => {
      const selectedLang = btn.getAttribute("data-lang");
      currentLanguage = selectedLang;
      sessionStorage.setItem("lang", selectedLang);
      updateTranslations();
    });
  });

  updateTranslations();
}

function updateTranslations() {
  const elements = document.querySelectorAll("[data-i18n]");
  const flagBtns = document.querySelectorAll(".lang-flag-btn");

  // Update active flag visual highlight
  flagBtns.forEach(btn => {
    if (btn.getAttribute("data-lang") === currentLanguage) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });

  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[currentLanguage] && translations[currentLanguage][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.setAttribute("placeholder", translations[currentLanguage][key]);
      } else {
        el.innerText = translations[currentLanguage][key];
      }
    }
  });

  // Update HTML dynamic title & description metadata
  if (currentLanguage === "es") {
    document.title = "Chalet Premium en Venta - Stambolovo, Bulgaria";
  } else if (currentLanguage === "en") {
    document.title = "Premium Country House for Sale - Stambolovo, Bulgaria";
  } else {
    document.title = "Продава се реновирана къща - с. Стамболово, Павликени";
  }

  // Update dynamic links for WhatsApp
  updateWhatsAppLinks();
}

