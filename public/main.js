// Lightbox Vision Logic
function setupLightbox() {
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  const closeBtn = document.getElementById("lightboxClose");
  const prevBtn = document.getElementById("lightboxPrev");
  const nextBtn = document.getElementById("lightboxNext");

  closeBtn.addEventListener("click", () => {
    lightbox.classList.remove("show");
  });

  // Close when clicking outside of image
  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox || e.target === lightbox.querySelector('.lightbox-content')) {
      lightbox.classList.remove("show");
    }
  });

  prevBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    navigateLightbox(-1);
  });

  nextBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    navigateLightbox(1);
  });

  // Keyboard navigation
  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("show")) return;
    if (e.key === "Escape") lightbox.classList.remove("show");
    if (e.key === "ArrowLeft") navigateLightbox(-1);
    if (e.key === "ArrowRight") navigateLightbox(1);
  });
}

function openLightbox(index) {
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  
  currentPhotoIndex = index;
  lightboxImg.src = housePhotos[index].url;
  lightboxImg.alt = housePhotos[index].title;
  lightbox.classList.add("show");
}

function navigateLightbox(dir) {
  currentPhotoIndex += dir;
  if (currentPhotoIndex < 0) currentPhotoIndex = housePhotos.length - 1;
  if (currentPhotoIndex >= housePhotos.length) currentPhotoIndex = 0;

  const lightboxImg = document.getElementById("lightboxImg");
  // Smooth fade visual transition
  lightboxImg.style.opacity = 0;
  setTimeout(() => {
    lightboxImg.src = housePhotos[currentPhotoIndex].url;
    lightboxImg.alt = housePhotos[currentPhotoIndex].title;
    lightboxImg.style.opacity = 1;
  }, 150);
}

